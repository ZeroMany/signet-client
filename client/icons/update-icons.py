#!/usr/bin/env python3
"""
Installs an "aegis-simple-icons" icon pack into the Signet client.

Usage (from the repository's top folder):

    python3 client/icons/update-icons.py aegis-simple-icons-vNNN.zip

Download the .zip from https://github.com/alexbakker/aegis-simple-icons/releases
This replaces client/icons/aegis-simple-icons/ with the pack's contents and
rewrites client/icons/icons.qrc, the list of files compiled into the app.
Rebuild the app afterwards.
"""
import json
import os
import shutil
import sys
import zipfile

HERE = os.path.dirname(os.path.abspath(__file__))
PACK_DIR = os.path.join(HERE, "aegis-simple-icons")
QRC_FILE = os.path.join(HERE, "icons.qrc")


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    with zipfile.ZipFile(sys.argv[1]) as z:
        pack = json.loads(z.read("pack.json"))
        files = ["pack.json"] + [icon["filename"] for icon in pack["icons"]]
        for name in files:
            # Refuse odd paths so a bad zip can't write outside the pack folder
            if name.startswith("/") or ".." in name.split("/"):
                sys.exit(f"unexpected path in pack: {name}")
        shutil.rmtree(PACK_DIR, ignore_errors=True)
        for name in files:
            target = os.path.join(PACK_DIR, name)
            os.makedirs(os.path.dirname(target), exist_ok=True)
            with open(target, "wb") as f:
                f.write(z.read(name))

    with open(QRC_FILE, "w", newline="\n") as f:
        f.write("<!-- Generated by update-icons.py. Do not edit by hand. -->\n")
        f.write("<RCC>\n    <qresource prefix=\"/icons\">\n")
        for name in sorted(files):
            f.write(f"        <file>aegis-simple-icons/{name}</file>\n")
        f.write("    </qresource>\n</RCC>\n")

    print(f"Installed {pack['name']} version {pack['version']} "
          f"({len(pack['icons'])} icons)")


if __name__ == "__main__":
    main()
